/**
 * Контракт приглашений (MVP scope: саморегистрации нет, пользователя
 * приглашает администратор).
 *
 * Провайдер доставки письма еще не выбран (docs/25-open-questions.md), поэтому
 * эндпоинт создания приглашения возвращает `token` один раз: администратор
 * передает его вручную. Ссылку на рассылку добавит отдельный issue, контракт
 * при этом не изменится.
 */

import type { UserRole } from './domain';

export interface UserInviteView {
  id: string;
  email: string;
  role: UserRole;
  expiresAt: string;
  createdAt: string;
}

/** Ответ `POST /api/v1/users/invites`: токен показывается только здесь. */
export interface UserInviteCreated extends UserInviteView {
  /** Токен приглашения. Передается пользователю и не хранится в открытом виде. */
  token: string;
  /**
   * Короткий код для ввода в приложении (ADR-0014).
   *
   * Показывается один раз: в базе только хеш. Нужен тренеру, который ставит
   * приложение и не открывает ссылки из браузера.
   */
  code: string;
}

/**
 * Что видно по токену приглашения до его принятия.
 *
 * Отдается публично (без сессии): ссылку открывает приглашенный человек, у
 * которого еще нет аккаунта. Поэтому в ответе минимум: адрес, роль и срок.
 *
 * Email нужен обязательно: форма показывает, на какой адрес выдано приглашение,
 * и человек сразу видит опечатку администратора. Без этого он заполнил бы пароль
 * и получил `INVITE_EMAIL_MISMATCH` без объяснения.
 */
export interface UserInvitePreview {
  email: string;
  role: UserRole;
  expiresAt: string;
}
