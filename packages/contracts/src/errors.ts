/** Тело ошибки, отдаваемое клиентам. */
export interface ApiErrorBody {
  code: ApiErrorCode;
  message: string;
  details?: Record<string, unknown>;
  /** correlation id запроса, для сопоставления с логами. */
  requestId?: string;
}

